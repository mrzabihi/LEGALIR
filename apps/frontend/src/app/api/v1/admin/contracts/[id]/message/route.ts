// ============================================================
// LEGALIR — /api/v1/admin/contracts/[id]/message
// ============================================================
// §6 — the printable admin message.
//
// One message per contract, at most 100 characters, printed in RED on the
// last page of the final PDF inside the printable area (and nowhere else).
//
// Rules enforced here, not in the UI:
//   • the limit is counted in code points, the same way the counter shows
//     it — a Persian text of 100 characters is accepted, 101 is rejected;
//   • an empty string REMOVES the message, so "no message" prints no red
//     card and reserves no empty space;
//   • only `admin:contracts:review` holders may write it;
//   • the change (author, time, and the before → after text) lands in the
//     platform audit log, so who wrote what survives an edit.
//
// The PDF is NOT re-rendered here: the final artifact is regenerated by
// the finalizer, which reads this row on every run. That keeps one
// rendering path and guarantees the preview, the PDF and the admin view
// are produced from the same source.
// ============================================================

import { NextResponse } from "next/server";
import type { NextRequest } from "next/server";
import { CONTRACT_ADMIN_MESSAGE_MAX } from "@legalir/types";
import { requirePermission } from "@/lib/rbac";
import { findUserById } from "@/lib/db";
import { recordAudit } from "@/lib/admin/audit";
import { adminError, readJson, requestMeta } from "@/lib/admin/http";
import { getContractById } from "@/lib/contracts/db";
import { adminMessageLength, getAdminMessage, setAdminMessage } from "@/lib/contracts/admin-print";
import { refreshFinalArtifact } from "@/lib/contracts/finalization";

interface Params {
  params: Promise<{ id: string }>;
}

export async function GET(request: NextRequest, { params }: Params): Promise<NextResponse> {
  const auth = requirePermission(request, "admin:contracts:read");
  if (!auth.ok) return auth.response;
  const { id } = await params;

  const contract = getContractById(id);
  if (!contract) return adminError(404, "NOT_FOUND", "قرارداد یافت نشد");

  const message = getAdminMessage(contract.id);
  return NextResponse.json({
    data: {
      message,
      maxChars: CONTRACT_ADMIN_MESSAGE_MAX,
      remainingChars: CONTRACT_ADMIN_MESSAGE_MAX - adminMessageLength(message?.messageFa ?? ""),
    },
  });
}

export async function POST(request: NextRequest, { params }: Params): Promise<NextResponse> {
  const auth = requirePermission(request, "admin:contracts:review");
  if (!auth.ok) return auth.response;
  const { id } = await params;

  const contract = getContractById(id);
  if (!contract) return adminError(404, "NOT_FOUND", "قرارداد یافت نشد");

  const body = (await readJson(request)) as { messageFa?: unknown } | null;
  if (!body || typeof body.messageFa !== "string") {
    return adminError(400, "MESSAGE_REQUIRED", "متن پیام الزامی است");
  }

  const previous = getAdminMessage(contract.id);
  const actor = findUserById(auth.ctx.userId);
  const actorLabelFa = actor?.displayName?.trim() || "مدیر لیگالیر";

  const result = setAdminMessage({
    contractId: contract.id,
    messageFa: body.messageFa,
    adminUserId: auth.ctx.userId,
    adminLabelFa: actorLabelFa,
  });

  if (!result.ok) {
    // 400 with the shared Persian text so the card can print it verbatim
    // under the counter instead of a generic failure.
    return adminError(400, result.code, result.errorFa);
  }

  recordAudit({
    actorUserId: auth.ctx.userId,
    actorRole: auth.ctx.role,
    orgId: auth.ctx.orgId,
    action:
      result.message === null
        ? "contract.admin_message.cleared"
        : previous
          ? "contract.admin_message.updated"
          : "contract.admin_message.set",
    resourceType: "property_contract",
    resourceId: contract.id,
    reason: null,
    before: { messageFa: previous?.messageFa ?? null },
    after: {
      messageFa: result.message?.messageFa ?? null,
      length: adminMessageLength(result.message?.messageFa ?? ""),
      adminLabelFa: result.message?.adminLabelFa ?? actorLabelFa,
    },
    ...requestMeta(request),
  });

  // T7 — a finalized contract's stored PDF is replaced so the archived copy
  // shows exactly what the preview shows. A contract still in progress has
  // no artifact yet; its PDF is rendered on demand and at finalization.
  const artifact = await refreshFinalArtifact({
    contractId: contract.id,
    actorId: auth.ctx.userId,
    baseUrl: new URL(request.url).origin,
  });

  return NextResponse.json({
    data: {
      message: result.message,
      maxChars: CONTRACT_ADMIN_MESSAGE_MAX,
      remainingChars:
        CONTRACT_ADMIN_MESSAGE_MAX - adminMessageLength(result.message?.messageFa ?? ""),
      /** Whether the stored final PDF was regenerated by this change. */
      finalArtifactRegenerated: artifact !== null,
    },
  });
}
