// Declared once and consumed by both the OpenGraph and Twitter blocks in
// `app/layout.tsx`. A `twitter:image` that disagrees with `og:image` is a
// silent inconsistency no other gate would catch, so the two read this
// constant rather than repeating the path.
//
// It lives in `lib/` rather than inline in the layout for one measurable
// reason: `app/layout.tsx` side-effect-imports `globals.css`, so any unit test
// that imports the layout drags a stylesheet edge into the affected-test graph
// and makes a CSS change look observable to the unit suite — which it never is
// (see `scripts/affected.mjs --selftest`). Keeping the descriptor style-free
// keeps that invariant intact.
//
// The image itself is generated by `scripts/generate-og-image.mjs`.
// ============================================================

